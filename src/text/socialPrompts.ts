export function getPromptForPostType(
  postType: PostType,
  platform: SocialTextPlatform,
  options: { publicationKind?: "text" | "caption"; target?: number } = {}
): string {
  const businessPrompt = PROMPTS[platform][postType as BusinessPostType];
  const prompt = withClientContentRules(
    businessPrompt ?? FORMAT_ONLY_PROMPT,
    postType,
    platform,
    Boolean(businessPrompt)
  );

  if (platform === "telegram" && options.publicationKind === "caption") {
    return withTelegramCaptionRules(prompt, options.target ?? 950);
  }

  return prompt;
}

function withClientContentRules(
  prompt: string,
  postType: PostType,
  platform: SocialTextPlatform,
  hasBusinessFooter: boolean
): string {
  const rules = [
    "Дополнительные правила клиента:",
    "— Отделяй каждый новый смысловой абзац и любой подзаголовок пустой строкой. Перед блоком вроде «Почему стоит посетить?» обязательно должна быть пустая строка; каждый пункт списка начинай с новой строки.",
    "— Используй настоящие переносы строк. Никогда не выводи символ обратного слэша `\\` как способ переноса.",
    "— Не используй обезличенные обороты вроде «это важно для клиентов/покупателей» и не объясняй, что пост написан для клиентов. Обращайся к читателю напрямую и описывай конкретную пользу, маршрут, условие или действие."
  ];

  if (postType !== "promo") {
    rules.push(
      "— Используй 4–7 уместных эмодзи, не считая маркеров списка: выделяй ими заголовки и подзаголовки. Каждый пункт характеристик, преимуществ, условий, маршрутов или других перечислений начинай с отдельного смыслового эмодзи. Не перегружай одну строку несколькими смайлами."
    );
  }

  if (hasBusinessFooter) {
    rules.push(
      platform === "telegram"
        ? "— В Telegram-посте в блоке «Следите за нами» оставь только ссылки на MAX и ВК. Ссылку на Telegram не добавляй: читатель уже находится в Telegram-канале."
        : "— В MAX-посте в блоке «Следите за нами» оставь только ссылки на Telegram и ВК. Ссылку на MAX не добавляй: читатель уже находится в канале MAX."
    );
  }

  return [prompt, "", ...rules].join("\n");
}

function withTelegramCaptionRules(prompt: string, target: number): string {
  const captionLengthRule =
    `— Длина поста: не более ${target} символов. Это общий лимит Telegram-подписи к фото/альбому, включая заголовок, основной текст, CTA, блок «Следите за нами» и хэштеги.`;
  const normalizedPrompt = prompt.replace(
    /— Длина поста: не более 1200 символов\./g,
    captionLengthRule
  );

  return [
    normalizedPrompt,
    "",
    "Дополнительные правила для Telegram-поста с фото:",
    `— Итоговый текст публикуется как подпись к фото/альбому, поэтому строго уложи весь пост в ${target} символов.`,
    "— CTA и блок «Следите за нами» обязательны и должны остаться целыми: не сокращай ссылки, не заменяй строки многоточием.",
    "— Если места не хватает, сокращай только основной блок, детали, преимущества и контекст."
  ].join("\n");
}
