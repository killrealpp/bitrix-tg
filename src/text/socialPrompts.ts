export function getPromptForPostType(postType: PostType): string {
  switch (postType) {
    case "event":
      return withPlatformRules(EVENT_PROMPT);
    case "promo":
      return withPlatformRules(PROMO_PROMPT);
    case "company_news":
      return withPlatformRules(COMPANY_NEWS_PROMPT);
    case "product_new":
      return withPlatformRules(PRODUCT_NEW_PROMPT);
    default:
      return withPlatformRules(FORMAT_ONLY_PROMPT);
  }
}

function withPlatformRules(prompt: string): string {
  return `${prompt}\n\n${PLATFORM_RULES}`;
}
